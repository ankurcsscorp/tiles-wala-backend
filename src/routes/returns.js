import {requirePermission} from '../middleware/permissions.js';
import express from 'express';
import {requireAuth} from '../middleware/auth.js';
import {approveSalesReturn,createReturn,getReturnById,listReturns,postReturn,eligibleReturnInvoices,returnInvoiceSource,previewReturn,updateReturn,finalizeReturn,changeReturnStatus,inspectReturn,applyReturnCredit,returnPartyBalance,returnSummary} from '../controllers/returns.js';
const router=express.Router();
router.use(requireAuth,requirePermission('returns'));
router.get('/',listReturns);
router.get('/summary',returnSummary);
router.get('/eligible-invoices',eligibleReturnInvoices);
router.get('/party-balance',returnPartyBalance);
router.get('/invoice/:type/:id',returnInvoiceSource);
router.post('/:type/preview',previewReturn);
router.get('/:id',getReturnById);
router.post('/:type',createReturn);
router.put('/:type/:id',updateReturn);
router.post('/sales/:id/approve',approveSalesReturn);
router.post('/:type/:id/post',postReturn);
router.post('/:type/:id/finalize',finalizeReturn);
router.post('/sales/:id/inspection',inspectReturn);
router.post('/:type/:id/apply-credit',applyReturnCredit);
router.post('/:type/:id/:action', (req,res,next)=>['cancel','reverse'].includes(req.params.action)?changeReturnStatus(req,res):next());
export default router;
