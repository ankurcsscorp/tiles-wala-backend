import {requirePermission} from '../middleware/permissions.js';
import express from "express";
import { requireAuth } from "../middleware/auth.js";
import { cancelFinalizedSales, cancellationHistory, cancellationPreview, cancelSales, createSalesDraft, finalizeSales, getSales, listSales, recordSalesPayment, reverseSales, salesBonusPreview, updateSalesDraft, previewSalesInvoiceRevision, reviseSalesInvoiceOperationalDetails, salesInvoiceRevisionHistory } from "../controllers/sales.js";

const router=express.Router();
router.use(requireAuth,requirePermission('sales'));
router.get("/",listSales);
router.post("/",createSalesDraft);
router.post("/bonus-preview",salesBonusPreview);
router.get("/:id",getSales);
router.get("/:id/revisions",salesInvoiceRevisionHistory);
router.post("/:id/revision-preview",previewSalesInvoiceRevision);
router.post("/:id/revisions",reviseSalesInvoiceOperationalDetails);
router.get("/:id/cancellation-preview",cancellationPreview);
router.get("/:id/cancellation-history",cancellationHistory);
router.put("/:id",updateSalesDraft);
router.post("/:id/finalize",finalizeSales);
router.post("/:id/payments",requirePermission("payments","manage"),recordSalesPayment);
router.post("/:id/cancel",cancelSales);
router.post("/:id/cancel-finalized",cancelFinalizedSales);
router.post("/:id/reverse",reverseSales);
export default router;
